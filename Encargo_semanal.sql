-- 5. Generacion de los Informes Finales (Caso 4)

-- Informe 1: Mecanicos sin bono y con impuesto bajo 40.000
SELECT 
    id_mecanico AS "ID MECANICO",
    primer_nombre || ' ' || ap_paterno AS "NOMBRE MECANICO",
    sueldo AS "SALARIO",
    monto_impuesto AS "IMPUESTO ACTUAL",
    (monto_impuesto * 0.8) AS "IMPUESTO REBAJADO", 
    sueldo - (monto_impuesto * 0.8) AS "SUELDO CON REBAJA IMPUESTOS"
FROM MECANICO
WHERE bono_jefatura IS NULL 
  AND monto_impuesto < 40000
ORDER BY "IMPUESTO ACTUAL" DESC, ap_paterno ASC;

-- Informe 2: Ajuste salarial del 5%
SELECT 
    id_mecanico AS "IDENTIFICADOR",
    primer_nombre || ' ' || segundo_nombre || ' ' || ap_paterno AS "MECANICO",
    sueldo AS "SALARIO ACTUAL",
    (sueldo * 0.05) AS "AJUSTE", 
    (sueldo * 1.05) AS "SUELDO REAJUSTADO"
FROM MECANICO
WHERE (sueldo BETWEEN 600000 AND 900000) 
   OR id_supervisor IS NULL
ORDER BY "SALARIO ACTUAL" ASC, "MECANICO" DESC;