-- 1. Creacion de tablas principales (sin claves foraneas)
CREATE TABLE PAIS (
    id_pais NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 9 INCREMENT BY 3),
    nombre VARCHAR2(50),
    CONSTRAINT pk_pais PRIMARY KEY (id_pais)
);

CREATE TABLE CIUDAD (
    id_ciudad NUMBER,
    nombre VARCHAR2(50),
    id_pais NUMBER,
    CONSTRAINT pk_ciudad PRIMARY KEY (id_ciudad),
    CONSTRAINT fk_ciudad_pais FOREIGN KEY (id_pais) REFERENCES PAIS(id_pais)
);

CREATE TABLE SUCURSAL (
    id_sucursal NUMBER,
    direccion VARCHAR2(100),
    telefono VARCHAR2(20),
    id_ciudad NUMBER,
    CONSTRAINT pk_sucursal PRIMARY KEY (id_sucursal),
    CONSTRAINT fk_sucursal_ciudad FOREIGN KEY (id_ciudad) REFERENCES CIUDAD(id_ciudad)
);

CREATE TABLE MECANICO (
    id_mecanico NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 400 INCREMENT BY 7),
    primer_nombre VARCHAR2(50),
    segundo_nombre VARCHAR2(50),
    ap_paterno VARCHAR2(50),
    sueldo NUMBER,
    monto_impuesto NUMBER,
    bono_jefatura NUMBER,
    id_supervisor NUMBER,
    CONSTRAINT pk_mecanico PRIMARY KEY (id_mecanico),
    CONSTRAINT fk_mecanico_supervisor FOREIGN KEY (id_supervisor) REFERENCES MECANICO(id_mecanico)
);

CREATE TABLE CLIENTE (
    id_cliente NUMBER,
    rut VARCHAR2(10),
    dv CHAR(1),
    primer_nombre VARCHAR2(50),
    ap_paterno VARCHAR2(50),
    email VARCHAR2(100),
    telefono VARCHAR2(20),
    CONSTRAINT pk_cliente PRIMARY KEY (id_cliente)
);

CREATE TABLE AUTOMOVIL (
    patente VARCHAR2(10),
    marca VARCHAR2(50),
    modelo VARCHAR2(50),
    anio NUMBER,
    id_cliente NUMBER,
    CONSTRAINT pk_automovil PRIMARY KEY (patente),
    CONSTRAINT fk_auto_cliente FOREIGN KEY (id_cliente) REFERENCES CLIENTE(id_cliente)
);

CREATE TABLE SERVICIO (
    id_servicio NUMBER,
    descripcion VARCHAR2(100),
    valor NUMBER,
    CONSTRAINT pk_servicio PRIMARY KEY (id_servicio)
);

-- Creacion de tabla mantencion con PK simple (se modificara despues en el caso 2)
CREATE TABLE MANTENCION (
    id_mantencion NUMBER,
    fecha DATE,
    estado VARCHAR2(20),
    costo_total NUMBER,
    id_sucursal NUMBER,
    id_mecanico NUMBER,
    patente VARCHAR2(10),
    CONSTRAINT pk_mantencion_inicial PRIMARY KEY (id_mantencion),
    CONSTRAINT fk_mant_sucursal FOREIGN KEY (id_sucursal) REFERENCES SUCURSAL(id_sucursal),
    CONSTRAINT fk_mant_mecanico FOREIGN KEY (id_mecanico) REFERENCES MECANICO(id_mecanico),
    CONSTRAINT fk_mant_auto FOREIGN KEY (patente) REFERENCES AUTOMOVIL(patente)
);

CREATE TABLE DETALLE_SERVICIO (
    id_mantencion NUMBER,
    id_servicio NUMBER,
    id_sucursal NUMBER, 
    CONSTRAINT pk_detalle PRIMARY KEY (id_mantencion, id_servicio),
    CONSTRAINT fk_detalle_mant_inicial FOREIGN KEY (id_mantencion) REFERENCES MANTENCION(id_mantencion),
    CONSTRAINT fk_detalle_serv FOREIGN KEY (id_servicio) REFERENCES SERVICIO(id_servicio)
);

